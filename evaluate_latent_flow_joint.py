"""
Evaluate a trained joint flow matching model:

  1. Distributional fidelity (FID / KID) per concentration and pooled,
     comparing real cells against cells generated by inverting real DMSO
     controls to noise and re-integrating the forward ODE at each target
     concentration (Sec. 4.3 / Table 2 in the paper).
  2. Dose-conditioned cell morphs by inversion: encode a real control cell,
     invert to noise, then forward-integrate at each target concentration
     (Sec. 3.3), producing a morph strip per source cell that preserves
     cell identity.

FID/KID require an offline Inception-v3 checkpoint (see --inception_path and
the README for how to obtain and point to it if the eval host has no
internet access).
"""
