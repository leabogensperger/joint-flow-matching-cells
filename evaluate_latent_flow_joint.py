# ─────────────────────────────────────────────────────────────────────────────
# Inception / FID / KID
# ─────────────────────────────────────────────────────────────────────────────
def load_inception(weights_path, device):
    """Load an offline Inception-v3 checkpoint for FID/KID feature extraction.
    See the README for how to obtain this file on a host without internet access."""
    import torchvision.models as tv
    import torch.nn as nn
    model = tv.inception_v3(weights=None, aux_logits=True, transform_input=False)
    model.load_state_dict(torch.load(weights_path, map_location=device))
    model.fc = nn.Identity()
    model.aux_logits = False
    model = model.to(device).eval()
    for p in model.parameters():
        p.requires_grad = False
    return model


@torch.no_grad()
def inception_features(images, inception, device, batch_size=32):
    """images: [N, C, H, W] in [0, 1]. Returns [N, 2048] numpy."""
    mean = torch.tensor([0.485, 0.456, 0.406], device=device).view(1, 3, 1, 1)
    std = torch.tensor([0.229, 0.224, 0.225], device=device).view(1, 3, 1, 1)
    feats = []
    for i in range(0, len(images), batch_size):
        batch = images[i:i + batch_size].to(device)
        batch = F.interpolate(batch, size=(299, 299), mode='bilinear', align_corners=False)
        batch = (batch - mean) / std
        feats.append(inception(batch).cpu().numpy())
    return np.concatenate(feats, axis=0)


def frechet_distance(mu1, sigma1, mu2, sigma2):
    diff = mu1 - mu2
    covmean, _ = scipy.linalg.sqrtm(sigma1 @ sigma2, disp=False)
    if np.iscomplexobj(covmean):
        covmean = covmean.real
    return float(diff @ diff + np.trace(sigma1 + sigma2 - 2 * covmean))


def kid_unbiased(real_feats, gen_feats, degree=3):
    """Unbiased KID via a degree-3 polynomial kernel on Inception features."""
    m, n = len(real_feats), len(gen_feats)
    d = real_feats.shape[1]

    def poly(X, Y):
        return (X @ Y.T / d + 1.0) ** degree

    k_rr, k_gg, k_rg = poly(real_feats, real_feats), poly(gen_feats, gen_feats), poly(real_feats, gen_feats)
    kid = ((k_rr.sum() - np.trace(k_rr)) / (m * (m - 1))
           + (k_gg.sum() - np.trace(k_gg)) / (n * (n - 1))
           - 2 * k_rg.mean())
    return float(kid)


# ─────────────────────────────────────────────────────────────────────────────
# VAE encode/decode, ODE solvers
# ─────────────────────────────────────────────────────────────────────────────
@torch.no_grad()
def encode(vae, images, scale_factor, device):
    mu, _ = vae.encode(images.to(device))
    return mu * scale_factor


@torch.no_grad()
def decode(vae, latents, scale_factor):
    return vae.decode(latents / scale_factor).clamp(0, 1)


@torch.no_grad()
def invert_ode(model, z_latent, c_value, device, steps=200):
    """Invert an encoded latent -> noise at a fixed concentration (Eq. 10)."""
    B = z_latent.shape[0]
    z = z_latent.clone()
    c_batch = torch.full((B,), float(c_value), dtype=torch.float32, device=device)

    dt = 1.0 / steps
    for i in reversed(range(steps)):
        t_z = torch.full((B,), i / steps, device=device)
        t_c = torch.ones(B, device=device)
        v_z, _ = model(z, t_z, t_c, c_scalar=c_batch)
        z = z - v_z * dt
    return z


@torch.no_grad()
def forward_ode(model, z_start, c_value, device, steps=200):
    """Forward-integrate a latent from t_z=0 to t_z=1 at a fixed concentration
    (Eq. 11 for morphing by inversion; also used for pure-noise generation)."""
    B = z_start.shape[0]
    z = z_start.clone()
    c_t = torch.full((B,), float(c_value), dtype=torch.float32, device=device)

    dt = 1.0 / steps
    for i in range(steps):
        t_z = torch.full((B,), i / steps, device=device)
        t_c = torch.ones(B, device=device)
        v_z, _ = model(z, t_z, t_c, c_scalar=c_t)
        z = z + v_z * dt
    return z


# ─────────────────────────────────────────────────────────────────────────────
# Model / checkpoint loading
# ─────────────────────────────────────────────────────────────────────────────
def load_flow_model(cfg, ckpt_path, device):
    model = JointFlowUNet(
        dim=cfg['model']['dim'],
        dim_mults=tuple(cfg['model']['dim_mults']),
        channels=4,
        out_dim=4,
        resnet_block_groups=cfg['model']['resnet_block_groups'],
    ).to(device)
    ckpt = torch.load(ckpt_path, map_location=device)
    raw = ckpt.get('ema_state_dict', ckpt.get('model_state_dict'))
    state = {k.replace("module.", ""): v for k, v in raw.items() if k != "n_averaged"}
    model.load_state_dict(state)
    model.eval()
    print(f"[INFO] Loaded JointFlowUNet | epoch={ckpt.get('epoch', 0)} "
          f"| loss={ckpt.get('train_loss', 0.0):.6f}")
    return model


def resolve_checkpoint(exp_dir):
    exp_dir = pathlib.Path(exp_dir)
    best = exp_dir / "best_model.pt"
    if best.exists():
        return best
    ckpt_dir = exp_dir / "checkpoints"
    ckpt_files = list(ckpt_dir.glob("*.pt")) if ckpt_dir.exists() else []
    if not ckpt_files:
        raise FileNotFoundError(f"No checkpoint found in {exp_dir}")

    def _epoch(p):
        nums = re.findall(r'\d+', p.stem)
        return int(nums[-1]) if nums else -1

    return max((f for f in ckpt_files if _epoch(f) != -1), key=_epoch)


# ─────────────────────────────────────────────────────────────────────────────
# FID / KID via inversion (Table 2)
# ─────────────────────────────────────────────────────────────────────────────
@torch.no_grad()
def eval_fid_kid(model, vae, ds, scale_factor, device, eval_dir, drug,
                  steps, invert_steps, inception_path, batch_size=32):
    """
    Invert real DMSO controls -> noise, forward-generate at every target
    concentration, and compute FID/KID against real cells at that
    concentration. Reports per-concentration and pooled metrics.
    """
    if not inception_path or not pathlib.Path(inception_path).exists():
        raise FileNotFoundError(
            f"Inception checkpoint not found at '{inception_path}'. "
            "Pass --inception_path pointing to a local inception_v3 state dict "
            "(see the README for how to obtain one offline)."
        )
    inception = load_inception(inception_path, device)

    concs_drug = sorted(c for c in ds.df_tgt['concentration'].unique() if c > 0)
    c_dmso = ds.get_model_conc(0.0)
    tf = ds.transform

    dmso_rows = ds.df_tgt[np.isclose(ds.df_tgt['concentration'].values, 0.0)]
    assert len(dmso_rows) > 0, "No DMSO cells found to invert."
    dmso_imgs = torch.stack([tf(Image.open(os.path.join(ds.data_root, r['relpath'])).convert('RGB')) for _, r in dmso_rows.iterrows()])

    print(f"[FID/KID] Inverting {len(dmso_imgs)} DMSO control cells...")
    z_noise = []
    for i in tqdm(range(0, len(dmso_imgs), batch_size), desc="Inverting", leave=False):
        batch = dmso_imgs[i:i + batch_size]
        z = encode(vae, batch, scale_factor, device)
        z_noise.append(invert_ode(model, z, c_dmso, device, steps=invert_steps).cpu())
    z_noise = torch.cat(z_noise, dim=0)
    n_src = len(z_noise)

    rows = []
    all_real, all_gen = [], []
    for c_raw in concs_drug:
        real_rows = ds.df_tgt[(ds.df_tgt['concentration'] > 0) & np.isclose(ds.df_tgt['concentration'].values, c_raw)]
        if len(real_rows) == 0:
            print(f"  [WARN] No real images at c={c_raw}, skipping")
            continue
        real_imgs = torch.stack([tf(Image.open(os.path.join(ds.data_root, r['relpath'])).convert('RGB')) for _, r in real_rows.iterrows()])

        c_model = ds.get_model_conc(c_raw)
        gen_list = []
        for j in range(0, n_src, batch_size):
            z_batch = z_noise[j:j + batch_size].to(device)
            z_gen = forward_ode(model, z_batch, c_model, device, steps=steps)
            gen_list.append(decode(vae, z_gen, scale_factor).cpu())
        gen_imgs = torch.cat(gen_list, dim=0)[:n_src]

        real_feats = inception_features(real_imgs, inception, device, batch_size)
        gen_feats = inception_features(gen_imgs, inception, device, batch_size)
        fid = frechet_distance(real_feats.mean(0), np.cov(real_feats, rowvar=False),
                                gen_feats.mean(0), np.cov(gen_feats, rowvar=False))
        kid = kid_unbiased(real_feats, gen_feats)

        rows.append(dict(concentration=float(c_raw), n_real=len(real_imgs), n_gen=len(gen_imgs), fid=fid, kid=kid))
        print(f"  c={c_raw:.4g}uM | N_real={len(real_imgs)} N_gen={len(gen_imgs)} | FID={fid:.2f} KID={kid:.4f}")

        all_real.append(real_feats)
        all_gen.append(gen_feats)

    if all_real:
        real_all, gen_all = np.concatenate(all_real), np.concatenate(all_gen)
        fid_pool = frechet_distance(real_all.mean(0), np.cov(real_all, rowvar=False),
                                     gen_all.mean(0), np.cov(gen_all, rowvar=False))
        kid_pool = kid_unbiased(real_all, gen_all)
        rows.append(dict(concentration="pooled", n_real=len(real_all), n_gen=len(gen_all), fid=fid_pool, kid=kid_pool))
        print(f"  POOLED | N_real={len(real_all)} N_gen={len(gen_all)} | FID={fid_pool:.2f} KID={kid_pool:.4f}")

    df = pd.DataFrame(rows)
    out_csv = eval_dir / f"fid_kid_{drug}.csv"
    df.to_csv(out_csv, index=False)
    print(f"[FID/KID] Saved -> {out_csv}")
    return df


