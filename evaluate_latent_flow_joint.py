def _font(size=13):
    try:
        # matplotlib bundles DejaVu Sans, giving a portable TTF across platforms
        import matplotlib
        font_path = os.path.join(matplotlib.get_data_path(), "fonts", "ttf", "DejaVuSans-Bold.ttf")
        return ImageFont.truetype(font_path, size)
    except Exception:
        return ImageFont.load_default()


def _label_columns(img_pil, labels):
    draw = ImageDraw.Draw(img_pil)
    font = _font()
    cell_w = img_pil.width // len(labels)
    for i, label in enumerate(labels):
        draw.text((i * cell_w + 4, 4), label, fill=(0, 0, 0), font=font)
        draw.text((i * cell_w + 3, 3), label, fill=(255, 255, 255), font=font)
    return img_pil


def _save_grid(cols, labels, out_path):
    n_rows = cols[0].shape[0]
    all_imgs = [cols[c][r] for r in range(n_rows) for c in range(len(cols))]
    grid = vutils.make_grid(torch.stack(all_imgs), nrow=len(cols), padding=2, normalize=True)
    img_pil = Image.fromarray(grid.mul(255).clamp(0, 255).permute(1, 2, 0).byte().numpy())
    img_pil = _label_columns(img_pil, labels)
    img_pil.save(out_path)


@torch.no_grad()
def generate_morphs_by_inversion(model, vae, ds, scale_factor, device, eval_dir, drug,
                                  steps, invert_steps, n_cells=8):
    """Morph real control cells across concentrations by inverting each cell to
    noise and re-integrating the forward ODE at every target concentration
    (Sec. 3.3): a morph strip per source cell that preserves cell identity."""
    concs_drug = sorted(c for c in ds.df_tgt['concentration'].unique() if c > 0)
    c_dmso = ds.get_model_conc(0.0)
    labels = ["control"] + [f"{c:.3g}uM" for c in concs_drug]

    dmso_rows = ds.df_tgt[np.isclose(ds.df_tgt['concentration'].values, 0.0)].iloc[:n_cells]
    n_cells = len(dmso_rows)
    tf = ds.transform
    src_imgs = torch.stack([tf(Image.open(os.path.join(ds.data_root, r['relpath'])).convert('RGB')) for _, r in dmso_rows.iterrows()])

    z_src = encode(vae, src_imgs, scale_factor, device)
    z_noise = invert_ode(model, z_src, c_dmso, device, steps=invert_steps)

    cols = [src_imgs]
    npz = {"src": src_imgs.numpy().astype(np.float32)}
    for c_raw in concs_drug:
        c_model = ds.get_model_conc(c_raw)
        z_gen = forward_ode(model, z_noise, c_model, device, steps=steps)
        imgs_gen = decode(vae, z_gen, scale_factor).cpu()
        cols.append(imgs_gen)
        npz[f"morph_{c_raw:.6g}".replace(".", "_")] = imgs_gen.numpy().astype(np.float32)

    np.savez(eval_dir / f"morphs_{drug}.npz", **npz)
    _save_grid(cols, labels, eval_dir / f"morphs_{drug}.png")
    print(f"[MORPH/inversion] {n_cells} cells x {len(concs_drug)} concentrations -> {eval_dir}")


# ─────────────────────────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────────────────────────
def main():
    p = argparse.ArgumentParser(description="Evaluate the joint latent flow matching model")
    p.add_argument("--exp", type=str, required=True,
                    help="Experiment name under experiments/, e.g. latent_fm_joint_conc/<timestamp>_ONS76_C7_log10")
    p.add_argument("--split", type=str, default="test", choices=["val", "test"])
    p.add_argument("--steps", type=int, default=200, help="Forward ODE steps")
    p.add_argument("--invert_steps", type=int, default=200, help="Inversion ODE steps")
    p.add_argument("--n_morph_cells", type=int, default=8)
    p.add_argument("--batch_size", type=int, default=32)
    p.add_argument("--inception_path", type=str, default=None,
                    help="Path to an offline inception_v3 state dict (required for --skip_fid=False). "
                         "See the README if the eval host has no internet access.")
    p.add_argument("--skip_fid", action="store_true", help="Skip FID/KID (no Inception checkpoint needed).")
    p.add_argument("--skip_morphs", action="store_true", help="Skip morph generation.")
    p.add_argument("--data", type=str, default=None,
                    help="Override the metadata CSV baked into the checkpoint's config "
                         "(e.g. metadata/sample_metadata.csv, to demo a checkpoint — including "
                         "a downloaded pretrained one — against the small bundled sample instead "
                         "of the full dataset). With sample data, also pass --skip_fid: there "
                         "usually aren't enough images per concentration for a meaningful FID/KID.")
    p.add_argument("--data_root", type=str, default=None,
                    help="Override data_root; required together with --data.")
    args = p.parse_args()

    np.random.seed(42)
    torch.manual_seed(42)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    BASE_DIR = pathlib.Path(__file__).parent.resolve()
    exp_dir = BASE_DIR / "experiments" / args.exp
    if not exp_dir.exists():
        raise FileNotFoundError(f"Experiment not found: {exp_dir}")

    with open(exp_dir / "config.yaml") as f:
        cfg = yaml.safe_load(f)
    if args.data:
        assert args.data_root, "--data requires --data_root"
        cfg['data'], cfg['data_root'] = args.data, args.data_root
    t, m = cfg['training'], cfg['model']
    drug = t.get('drug', 'unknown')

    eval_dir = exp_dir / "evaluation"
    eval_dir.mkdir(exist_ok=True)

    # ── Load frozen VAE ───────────────────────────────────────────────────────
    vae = MicroscopyVAE(
        in_channels=cfg['vae']['in_channels'],
        latent_channels=cfg['vae']['latent_channels'],
        base_channels=cfg['vae'].get('base_channels', 64),
    ).to(device)
    vae, _ = load_ema_model(vae, BASE_DIR / cfg['vae']['checkpoint'], device)
    vae.eval()
    for prm in vae.parameters():
        prm.requires_grad = False

    # ── Load flow model ───────────────────────────────────────────────────────
    ckpt_path = resolve_checkpoint(exp_dir)
    model = load_flow_model(cfg, ckpt_path, device)

    scale_path = exp_dir / "latent_scale.pt"
    scale_factor = torch.load(scale_path)["scale_factor"] if scale_path.exists() else 1.0
    print(f"[INFO] Scale factor: {scale_factor:.4f}")

    # ── Dataset ───────────────────────────────────────────────────────────────
    ds = FlowCompoundDataset(
        csv_path=os.path.join(BASE_DIR, cfg['data']),
        cell_line=m['cell_line'],
        split=args.split,
        in_channels=cfg['vae']['in_channels'],
        transform=transforms.ToTensor(),
        data_root=os.path.join(BASE_DIR, cfg['data_root']),
        drug=drug,
        target_concentrations=t.get('target_concentrations', None),
        conc_transform=t.get('conc_transform', None),
        filtered_only=t.get('filtered_only', True),
        include_dmso_targets=t.get('include_dmso', True),
    )
    print(f"[INFO] Drug={drug} | concentrations={sorted(ds.df_tgt['concentration'].unique().tolist())}")

    # Tag output filenames with the data source so a run against sample_data/
    # doesn't overwrite results from a run against the real dataset.
    data_tag = pathlib.Path(cfg['data']).stem
    out_tag = drug if data_tag == "cell_lines_drug_compounds" else f"{drug}_{data_tag}"

    results = {}
    if not args.skip_fid:
        print("\n" + "=" * 70 + "\n[EVAL] FID / KID via inversion\n" + "=" * 70)
        df = eval_fid_kid(model, vae, ds, scale_factor, device, eval_dir, out_tag,
                           steps=args.steps, invert_steps=args.invert_steps,
                           inception_path=args.inception_path, batch_size=args.batch_size)
        results["fid_kid"] = df.to_dict(orient="records")

    if not args.skip_morphs:
        print("\n" + "=" * 70 + "\n[EVAL] Morph generation\n" + "=" * 70)
        generate_morphs_by_inversion(model, vae, ds, scale_factor, device, eval_dir, out_tag,
                                      steps=args.steps, invert_steps=args.invert_steps,
                                      n_cells=args.n_morph_cells)

    with open(eval_dir / f"summary_{out_tag}.json", "w") as f:
        json.dump(results, f, indent=2)
    print(f"\n[SUCCESS] All outputs -> {eval_dir}")


if __name__ == "__main__":
    main()
